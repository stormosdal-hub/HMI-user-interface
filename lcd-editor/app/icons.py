def _rotate_cw(rows):
    h = len(rows)
    return ["".join(rows[h - 1 - r][c] for r in range(h)) for c in range(len(rows[0]))]


ICONS_8["arrow_right"] = _rotate_cw(ICONS_8["arrow_up"])
ICONS_8["arrow_down"] = _rotate_cw(ICONS_8["arrow_right"])
ICONS_8["arrow_left"] = _rotate_cw(ICONS_8["arrow_down"])

ICONS = {**ICONS_8, **ICONS_16}

