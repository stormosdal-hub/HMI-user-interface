# Glyph -> ROM code, so custom glyphs that already exist in ROM cost no CGRAM slot.
ROM_BY_GLYPH = {}
for _code, _glyph in sorted(ROM.items(), reverse=True):
    ROM_BY_GLYPH[_glyph] = _code
ROM_BY_GLYPH[BLANK] = CODE_SPACE


def encode_char(ch):
    """Returns a ROM code (int), a custom glyph (tuple) or None if unsupported."""
    if ch in CHARMAP:
        return CHARMAP[ch]
    if ch in EXTRA:
        return EXTRA[ch]
    base = unicodedata.normalize("NFKD", ch)[:1]  # é -> e, Ä -> A
    if base != ch and base in CHARMAP:
        return CHARMAP[base]
    return None


