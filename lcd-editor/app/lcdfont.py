"""Character data for HD44780 LCDs (1602/2004 modules).

The LCD draws text from its own character ROM. Almost every module has the
"A00" (Japanese) ROM: ASCII plus a few Greek letters, ä, ö, ü, ° and katakana.
The ROM glyphs here only feed the editor preview. They are close to, but not
guaranteed identical with, what a given module shows.

Anything the ROM lacks (æ, ø, å, icons, bar segments, graphs) becomes a custom
glyph that is uploaded to the LCD's CGRAM, which has room for 8.

A glyph is a tuple of 8 row bitmasks, 5 bits wide (bit 4 = leftmost column).
"""

import unicodedata

WIDTH, HEIGHT = 5, 8
CUSTOM_SLOTS = 8
BLANK = (0,) * HEIGHT
FULL = (0x1F,) * HEIGHT
CODE_SPACE, CODE_UNKNOWN, CODE_FULL = 0x20, 0x3F, 0xFF


def art(rows):
    """'#'-art (8 rows of 5) -> glyph."""
    assert len(rows) == HEIGHT and all(len(r) == WIDTH for r in rows), rows
    return tuple(int(r.replace("#", "1").replace(".", "0"), 2) for r in rows)


def to_art(glyph):
    return [format(row, "05b").replace("1", "#").replace("0", ".") for row in glyph]


